import fs from 'node:fs';
let pass=0;
const checks=[];
const check=(name,ok)=>{checks.push([name,!!ok]);if(ok)pass++;else console.error('FAIL',name)};
const read=p=>fs.readFileSync(p,'utf8');
const admin=read('supabase/functions/comp-admin/index.ts');
const calc=read('supabase/functions/comp-calculations/index.ts');
const ui=read('universal-compensation-platform.js');
const qUi=read('comp-qualification-ui.js');
const tierMig=read('supabase/migrations/20260829_universal_compensation_tiers.sql');
const qualMig=read('supabase/migrations/20260829_universal_compensation_qualification_tracking.sql');
const publishMig=read('supabase/migrations/20260829_universal_compensation_publish_refresh.sql');
const index=read('index.html');
check('B040 build',admin.includes('B2026.08.29.040')&&calc.includes('B2026.08.29.040'));
check('editable base commission',admin.includes('base_rate')&&ui.includes('ucBaseRate')&&ui.includes('Save Draft Compensation'));
check('editable bonus rules',admin.includes('validateBonusRules')&&ui.includes('+ Add Bonus Rule'));
check('editable tier rules',admin.includes('validateTierRules')&&ui.includes('+ Add Tier'));
check('rate override changes base calculation',admin.includes('effectiveRate(plan, tiers')&&admin.includes('calcBase(plan'));
check('generic program creation',admin.includes('create_program')&&ui.includes('Create Program + Draft Plan'));
check('generic production adapter',tierMig.includes('comp_production_events')&&admin.includes('record_production_event'));
check('ACA enrollment adapter preserved',tierMig.includes("production_source='campaign_enrollments'")&&calc.includes('campaign_enrollments'));
check('qualification table',qualMig.includes('comp_qualification_snapshots'));
check('production events auto refresh',qualMig.includes('comp_production_event_qualification_refresh'));
check('ACA enrollments auto refresh',qualMig.includes('campaign_enrollment_qualification_refresh'));
check('plan publish rebuilds qualification',publishMig.includes('comp_plan_publish_qualification_refresh'));
check('bonus progress stored',qualMig.includes('bonus_progress')&&qualMig.includes("'units_needed'"));
check('agent bonus progress visible',qUi.includes('BONUS QUALIFICATION TRACKING')&&qUi.includes('QUALIFIED')&&qUi.includes('TO GO'));
check('published plan versioning',admin.includes('status: "published"')&&admin.includes('status: "retired"'));
check('universal UI loaded',index.includes('universal-compensation-platform.js'));
check('qualification UI loaded',index.includes('comp-qualification-ui.js'));
check('no fake qualification seeding',!qualMig.includes('insert into public.comp_production_events')&&!qualMig.includes('insert into public.campaign_enrollments'));
console.log(`Universal compensation live contract: ${pass}/${checks.length} PASS`);
